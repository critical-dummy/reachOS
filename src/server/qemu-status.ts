import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

/**
 * Expected asset specification for QEMU-WASM runtime.
 */
export interface QemuAssetSpec {
  readonly filename: string;
  readonly description: string;
  readonly category: 'runtime' | 'guest';
  readonly required: boolean;
  readonly upstreamStatus: 'confirmed' | 'provisional';
  readonly notes: string;
}

/**
 * Inspection result for an individual asset file.
 */
export interface QemuAssetFileStatus {
  readonly filename: string;
  readonly description: string;
  readonly category: 'runtime' | 'guest';
  readonly required: boolean;
  readonly upstreamStatus: 'confirmed' | 'provisional';
  readonly exists: boolean;
  readonly sizeBytes: number | null;
}

/**
 * High-level status indicating asset availability.
 * Note: 'assets_present_unverified' explicitly conveys that files exist,
 * but guest execution and boot have NOT been verified.
 */
export type QemuAssetStatus =
  | 'assets_missing'
  | 'assets_incomplete'
  | 'assets_present_unverified';

/**
 * Truthful response schema for /api/qemu/status.
 */
export interface QemuStatusResponse {
  readonly status: QemuAssetStatus;
  readonly bootVerified: false;
  readonly executionReady: false;
  readonly arch: 'aarch64';
  readonly assetDirectory: string;
  readonly directoryExists: boolean;
  readonly summary: {
    readonly requiredCount: number;
    readonly presentRequiredCount: number;
    readonly missingRequiredCount: number;
    readonly totalCheckedCount: number;
  };
  readonly missingRequired: readonly string[];
  readonly presentFiles: readonly string[];
  readonly assets: readonly QemuAssetFileStatus[];
  readonly notes: string;
}

/**
 * Asset manifest derived from upstream ktock/qemu-wasm documentation and examples.
 *
 * Confirmed upstream outputs:
 * - qemu-system-aarch64.js: Main Emscripten JavaScript runtime wrapper.
 * - qemu-system-aarch64.wasm: Compiled QEMU emulator WebAssembly module.
 * - qemu-system-aarch64.worker.js: Emscripten pthread Web Worker script for multi-threading.
 * - load.js: Preloaded virtual filesystem loader generated by Emscripten file_packager.py.
 * - load.data: Data binary bundle generated alongside load.js containing the guest kernel/initramfs.
 *   (Upstream also permits naming this qemu-system-aarch64.data depending on file_packager.py invocation).
 */
export const QEMU_AARCH64_MANIFEST: readonly QemuAssetSpec[] = [
  {
    filename: 'qemu-system-aarch64.js',
    description: 'Emscripten JavaScript runtime glue and loader',
    category: 'runtime',
    required: true,
    upstreamStatus: 'confirmed',
    notes: 'Generated by emmake/emcc during QEMU aarch64-softmmu build.',
  },
  {
    filename: 'qemu-system-aarch64.wasm',
    description: 'Compiled QEMU-WASM AArch64 emulator binary',
    category: 'runtime',
    required: true,
    upstreamStatus: 'confirmed',
    notes: 'Core WebAssembly binary containing TCG JIT compiler.',
  },
  {
    filename: 'qemu-system-aarch64.worker.js',
    description: 'Emscripten pthread Web Worker script',
    category: 'runtime',
    required: true,
    upstreamStatus: 'confirmed',
    notes: 'Required for PROXY_TO_PTHREAD multithreaded execution.',
  },
  {
    filename: 'load.js',
    description: 'Virtual filesystem preloader script',
    category: 'guest',
    required: true,
    upstreamStatus: 'confirmed',
    notes: 'Generated by Emscripten file_packager.py in upstream examples/raspi3ap.',
  },
  {
    filename: 'load.data',
    description: 'Packaged guest kernel, DTB, and initramfs binary bundle',
    category: 'guest',
    required: true,
    upstreamStatus: 'confirmed',
    notes: 'Generated alongside load.js. Upstream may alternate between load.data and qemu-system-aarch64.data.',
  },
];

/**
 * Alternative accepted filenames for guest data bundle.
 */
const ALTERNATIVE_DATA_FILENAMES = ['qemu-system-aarch64.data'];

/**
 * Resolves the filesystem path to the QEMU assets directory.
 * Uses a prioritized check across known project layout locations:
 * 1. Explicit override (used in testing or via parameter)
 * 2. QEMU_ASSET_DIR environment variable
 * 3. ./public/qemu in workspace root
 * 4. ../public/qemu relative to server source
 * 5. ../browser/qemu relative to built SSR server bundle
 */
export function resolveQemuAssetDirectory(overrideDir?: string): string {
  if (overrideDir) {
    return overrideDir;
  }
  if (process.env['QEMU_ASSET_DIR']) {
    return process.env['QEMU_ASSET_DIR'];
  }

  const currentDir = path.dirname(fileURLToPath(import.meta.url));

  const candidatePaths = [
    path.join(process.cwd(), 'public', 'qemu'),
    path.join(currentDir, '..', 'public', 'qemu'),
    path.join(currentDir, '..', 'browser', 'qemu'),
  ];

  for (const candidate of candidatePaths) {
    if (fs.existsSync(candidate)) {
      return candidate;
    }
  }

  return candidatePaths[0];
}

/**
 * Inspects the specified asset directory against the manifest and generates
 * a truthful status report.
 */
export function inspectQemuAssets(assetDirectory: string): QemuStatusResponse {
  const directoryExists = fs.existsSync(assetDirectory);

  const assetStatuses: QemuAssetFileStatus[] = [];
  const missingRequired: string[] = [];
  const presentFiles: string[] = [];

  for (const spec of QEMU_AARCH64_MANIFEST) {
    let filePath = path.join(assetDirectory, spec.filename);
    let fileExists = directoryExists && fs.existsSync(filePath);

    // If load.data is missing, check alternative accepted filename
    if (!fileExists && spec.filename === 'load.data' && directoryExists) {
      for (const alt of ALTERNATIVE_DATA_FILENAMES) {
        const altPath = path.join(assetDirectory, alt);
        if (fs.existsSync(altPath)) {
          filePath = altPath;
          fileExists = true;
          break;
        }
      }
    }

    let sizeBytes: number | null = null;
    if (fileExists) {
      try {
        const stat = fs.statSync(filePath);
        sizeBytes = stat.size;
      } catch {
        sizeBytes = null;
      }
      presentFiles.push(spec.filename);
    } else if (spec.required) {
      missingRequired.push(spec.filename);
    }

    assetStatuses.push({
      filename: spec.filename,
      description: spec.description,
      category: spec.category,
      required: spec.required,
      upstreamStatus: spec.upstreamStatus,
      exists: fileExists,
      sizeBytes,
    });
  }

  const requiredCount = QEMU_AARCH64_MANIFEST.filter((a) => a.required).length;
  const presentRequiredCount = requiredCount - missingRequired.length;

  let status: QemuAssetStatus;
  let notes: string;

  if (presentRequiredCount === 0) {
    status = 'assets_missing';
    notes =
      'No QEMU-WASM runtime assets found. Upstream build outputs and guest images must be provided in the assets directory.';
  } else if (missingRequired.length > 0) {
    status = 'assets_incomplete';
    notes = `Partial assets detected. Missing required files: ${missingRequired.join(', ')}.`;
  } else {
    status = 'assets_present_unverified';
    notes =
      'All declared required assets are present on disk. However, browser execution, WebAssembly instantiation, and guest Linux boot have NOT been verified.';
  }

  return {
    status,
    bootVerified: false,
    executionReady: false,
    arch: 'aarch64',
    assetDirectory,
    directoryExists,
    summary: {
      requiredCount,
      presentRequiredCount,
      missingRequiredCount: missingRequired.length,
      totalCheckedCount: QEMU_AARCH64_MANIFEST.length,
    },
    missingRequired,
    presentFiles,
    assets: assetStatuses,
    notes,
  };
}

/**
 * Convenience entry point for Express handler using default resolved asset directory.
 */
export function getQemuStatus(customDir?: string): QemuStatusResponse {
  const dir = resolveQemuAssetDirectory(customDir);
  return inspectQemuAssets(dir);
}

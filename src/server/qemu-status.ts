/**
 * Resolves the filesystem path to the QEMU assets directory.
 * Uses a prioritized check across known project layout locations:
 * 1. Explicit override (used in testing or via parameter)
 * 2. QEMU_ASSET_DIR environment variable
 * 3. ./public/qemu in workspace root
 * 4. ../public/qemu relative to server source
 * 5. ../browser/qemu relative to built SSR server bundle
 */
export function resolveQemuAssetDirectory(overrideDir?: string): string {
  if (overrideDir) {
    return overrideDir;
  }
  if (process.env['QEMU_ASSET_DIR']) {
    return process.env['QEMU_ASSET_DIR'];
  }

  const currentDir = path.dirname(fileURLToPath(import.meta.url));

  const candidatePaths = [
    path.join(process.cwd(), 'public', 'qemu'),
    path.join(currentDir, '..', 'public', 'qemu'),
    path.join(currentDir, '..', 'browser', 'qemu'),
  ];

  for (const candidate of candidatePaths) {
    if (fs.existsSync(candidate)) {
      return candidate;
    }
  }

  return candidatePaths[0];
}

/**
 * Inspects the specified asset directory against the manifest and generates
 * a truthful status report.
 */
export function inspectQemuAssets(assetDirectory: string): QemuStatusResponse {
  const directoryExists = fs.existsSync(assetDirectory);

  const assetStatuses: QemuAssetFileStatus[] = [];
  const missingRequired: string[] = [];
  const presentFiles: string[] = [];

  let loaderPackageName: string | null = null;
  let loaderCompatible = false;
  let loaderChecked = false;

  // 1. Inspect load.js if present to extract required package name
  const loadJsPath = path.join(assetDirectory, 'load.js');
  if (directoryExists && fs.existsSync(loadJsPath)) {
    try {
      const loadJsContent = fs.readFileSync(loadJsPath, 'utf8');
      loaderPackageName = extractPackageNameFromLoader(loadJsContent);
      loaderChecked = true;
    } catch {
      loaderPackageName = null;
    }
  }

  for (const spec of QEMU_AARCH64_MANIFEST) {
    let detectedFilename: string | null = null;
    let filePath = path.join(assetDirectory, spec.expectedFilename);
    let fileExists = directoryExists && fs.existsSync(filePath);

    if (fileExists) {
      detectedFilename = spec.expectedFilename;
    } else if (directoryExists && spec.alternativeFilenames) {
      for (const alt of spec.alternativeFilenames) {
        const altPath = path.join(assetDirectory, alt);
        if (fs.existsSync(altPath)) {
          filePath = altPath;
          fileExists = true;
          detectedFilename = alt;
          break;
        }
      }
    }

    // Special validation for the guest data bundle against load.js
    if (spec.id === 'guest-data') {
      if (loaderChecked && loaderPackageName) {
        // If load.js expects a specific package name, verify that the detected file matches
        if (detectedFilename === loaderPackageName) {
          loaderCompatible = true;
        } else {
          // File exists on disk, but does not match what load.js expects!
          loaderCompatible = false;
        }
      } else {
        // load.js is missing, unreadable, or unparseable: compatibility cannot be verified
        loaderCompatible = false;
      }
    }

    let sizeBytes: number | null = null;
    if (fileExists && detectedFilename) {
      try {
        const stat = fs.statSync(filePath);
        sizeBytes = stat.size;
      } catch {
        sizeBytes = null;
      }
      presentFiles.push(detectedFilename);
    } else if (spec.required) {
      missingRequired.push(spec.expectedFilename);
    }

    assetStatuses.push({
      id: spec.id,
      filename: spec.expectedFilename,
      expectedFilename: spec.expectedFilename,
      detectedFilename,
      description: spec.description,
      category: spec.category,
      required: spec.required,
      upstreamStatus: spec.upstreamStatus,
      exists: fileExists,
      sizeBytes,
    });
  }

  const requiredCount = QEMU_AARCH64_MANIFEST.filter((a) => a.required).length;
  const presentRequiredCount = requiredCount - missingRequired.length;
  const allRequiredPresent = missingRequired.length === 0;

  let status: QemuAssetStatus;
  let notes: string;

  if (presentRequiredCount === 0) {
    status = 'assets_missing';
    notes =
      'No QEMU-WASM runtime assets found. Upstream build outputs and guest images must be provided in the assets directory.';
  } else if (!allRequiredPresent) {
    status = 'assets_incomplete';
    notes = `Partial assets detected. Missing required files: ${missingRequired.join(', ')}.`;
  } else if (!loaderCompatible) {
    // All declared files are physically present on disk, but loader/data bundle compatibility failed
    status = 'assets_incomplete';
    if (!loaderChecked || !loaderPackageName) {
      notes =
        "Data loader 'load.js' exists but is unparseable; required package name could not be verified. Loader/data compatibility unconfirmed.";
    } else {
      const dataAsset = assetStatuses.find((a) => a.id === 'guest-data');
      notes = `Asset package mismatch: 'load.js' expects package '${loaderPackageName}', but detected '${dataAsset?.detectedFilename ?? 'unknown'}' on disk.`;
    }
  } else {
    status = 'assets_present_unverified';
    notes =
      'All declared required assets are present on disk and data loader compatibility is verified. However, browser execution, WebAssembly instantiation, and guest Linux boot have NOT been verified.';
  }

  return {
    status,
    bootVerified: false,
    executionReady: false,
    arch: 'aarch64',
    assetDirectory,
    directoryExists,
    loaderPackageName,
    loaderCompatible,
    summary: {
      requiredCount,
      presentRequiredCount,
      missingRequiredCount: missingRequired.length,
      totalCheckedCount: QEMU_AARCH64_MANIFEST.length,
    },
    missingRequired,
    presentFiles,
    assets: assetStatuses,
    notes,
  };
}

/**
 * Convenience entry point for Express handler using default resolved asset directory.
 */
export function getQemuStatus(customDir?: string): QemuStatusResponse {
  const dir = resolveQemuAssetDirectory(customDir);
  return inspectQemuAssets(dir);
}

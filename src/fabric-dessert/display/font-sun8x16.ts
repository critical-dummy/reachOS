export class ConsoleFontSun8x16 implements IConsoleFont {
  readonly name = "font_sun_8x16";
  readonly width = 8;
  readonly height = 16;
  readonly charCount = 256;
  readonly data: Uint8Array = FONT_DATA_SUN_8X16;

  getGlyph(charCode: number): Uint8Array {
    const code = charCode & 0xff;
    const offset = code * 16;
    return this.data.subarray(offset, offset + 16);
  }

  drawGlyph(
    framebuffer: IFramebuffer,
    x: number,
    y: number,
    charCode: number,
    fgR = 255,
    fgG = 255,
    fgB = 255,
    fgA = 255,
    bgR?: number,
    bgG?: number,
    bgB?: number,
    bgA?: number
  ): void {
    const glyph = this.getGlyph(charCode);
    for (let row = 0; row < 16; row++) {
      const py = y + row;
      if (py < 0 || py >= framebuffer.height) continue;
      const bits = glyph[row];
      for (let col = 0; col < 8; col++) {
        const px = x + col;
        if (px < 0 || px >= framebuffer.width) continue;
        const isSet = (bits & (0x80 >> col)) !== 0;
        if (isSet) {
          framebuffer.writePixel(px, py, fgR, fgG, fgB, fgA);
        } else if (bgR !== undefined && bgG !== undefined && bgB !== undefined) {
          framebuffer.writePixel(px, py, bgR, bgG, bgB, bgA ?? 255);
        }
      }
    }
  }

  drawString(
    framebuffer: IFramebuffer,
    x: number,
    y: number,
    text: string,
    fgR = 255,
    fgG = 255,
    fgB = 255,
    fgA = 255,
    bgR?: number,
    bgG?: number,
    bgB?: number,
    bgA?: number
  ): void {
    let curX = x;
    let curY = y;
    for (let i = 0; i < text.length; i++) {
      const ch = text.charCodeAt(i);
      if (ch === 10) {
        // newline
        curX = x;
        curY += this.height;
        continue;
      }
      if (ch === 13) {
        // carriage return
        curX = x;
        continue;
      }
      this.drawGlyph(framebuffer, curX, curY, ch, fgR, fgG, fgB, fgA, bgR, bgG, bgB, bgA);
      curX += this.width;
    }
  }
}

export const font_sun_8x16 = new ConsoleFontSun8x16();
